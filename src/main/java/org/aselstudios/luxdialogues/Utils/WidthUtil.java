   public static float getWidth(String textLine) {
      float width = 0.0F;

      for (char c : textLine.toCharArray()) {
         String charStr = String.valueOf(c);
         if (charStr.equalsIgnoreCase("*")) {
            width += 4.0F;
         } else if (widthMap.containsKey(charStr)) {
            width += widthMap.get(charStr) + 1.0F;
         } else if (widthMap2.containsKey(charStr)) {
            width += widthMap2.get(charStr) + 1.0F;
         } else if (MinecraftFont.Font.isValid(charStr)) {
            width += MinecraftFont.Font.getWidth(charStr) + 1.0F;
         }
      }

      return width;
   }

